#!/usr/bin/env python3
"""build.py — build tool (replacement for npm scripts).

  python scripts/build.py env     create js/env.js from the .env file
  python scripts/build.py css     build css/app.css from src/input.css (Tailwind, one-off)
  python scripts/build.py all     env + css
  python scripts/build.py watch   env once, then watch CSS files and rebuild when they change
  python scripts/build.py static  create the dist/ folder for static hosting

CSS requires:  pip install -r requirements-dev.txt   (pytailwindcss: standalone Tailwind binary, no Node.js).
The binary is downloaded automatically the first time it is used. This project uses Tailwind v3 (tailwind.config.js + @tailwind);
v4 uses different configuration, so the version is pinned below.
"""
import json, os, re, shutil, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TAILWIND_VERSION = 'v3.4.17'      # change here if you want another v3 version

# Only these front-end files are copied to dist/ for static hosting (server.py, data/, .env, and mcp.json stay private).
STATIC_FILES = ['index.html', 'app.html', 'models.html', 'login.html']
STATIC_DIRS = ['css', 'js', 'assets']

def build_env():
    """Read .env, take variables prefixed with LUNA_, write js/env.js (window.ENV)."""
    env, f = {}, ROOT / '.env'
    if f.exists():
        for line in f.read_text('utf-8').splitlines():
            m = re.match(r'^\s*(LUNA_[A-Z0-9_]+)\s*=\s*(.*?)\s*$', line)   # ignore comments and blank lines
            if m and m.group(2):                                              # skip empty values
                env[m.group(1)] = re.sub(r'^["\']|["\']$', '', m.group(2))
    out = '/* GENERATED by `python scripts/build.py env` from the .env file — do not edit manually. */\n'
    (ROOT / 'js' / 'env.js').write_text(out + 'window.ENV=' + json.dumps(env, indent=2, ensure_ascii=False) + ';\n', 'utf-8')
    print(f'env.js written ({len(env)} variables)')

def build_css(watch=False):
    try: import pytailwindcss  # noqa: F401
    except ImportError: sys.exit('pytailwindcss is required. Run: pip install -r requirements-dev.txt')
    args = [sys.executable, '-m', 'pytailwindcss', '-i', 'src/input.css', '-o', 'css/app.css', '--watch' if watch else '--minify']
    subprocess.run(args, cwd=ROOT, env={**os.environ, 'TAILWINDCSS_VERSION': TAILWIND_VERSION}, check=True)

def build_static():
    """Copy only the browser files to dist/. js/env.js is reset to empty so .env secrets are never published."""
    out = ROOT / 'dist'
    if out.exists(): shutil.rmtree(out)
    out.mkdir()
    for name in STATIC_FILES:
        shutil.copy2(ROOT / name, out / name)
    for name in STATIC_DIRS:
        ignore = shutil.ignore_patterns('env.js') if name == 'js' else None
        shutil.copytree(ROOT / name, out / name, ignore=ignore)
    (out / 'js' / 'env.js').write_text(
        '/* Static build: intentionally empty so secrets from .env are not published. */\nwindow.ENV={};\n', 'utf-8')
    (out / '.nojekyll').touch()          # GitHub Pages: serve files as-is (no Jekyll processing)
    print(f'Static site written to {out} ({len(STATIC_FILES)} pages)')

if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'all'
    if cmd == 'env': build_env()
    elif cmd == 'css': build_css()
    elif cmd == 'all': build_env(); build_css()
    elif cmd == 'watch': build_env(); build_css(watch=True)
    elif cmd == 'static': build_static()
    else: sys.exit(__doc__)
